/* ══════ 2. STATE & ELEMEN ══════
   lang dan theme disimpan di localStorage agar pilihan pengunjung diingat saat halaman dibuka lagi. */
const root = document.documentElement;
const $ = (selector) => document.querySelector(selector);
let lang = localStorage.getItem('lang') || 'id';
let theme = localStorage.getItem('theme') || 'dark';
/* ══════ 3. apply(): TERAPKAN BAHASA & TEMA ══════
   Mengisi semua elemen [data-i18n], membuat badge soft skill, mengatur label tombol, dan mengganti tema Bootstrap. */
function apply() {
 const d = T[lang];
 root.lang = lang;
 document.querySelectorAll('[data-i18n]').forEach((element) => {
  element.textContent = d[element.dataset.i18n] ?? element.textContent;
 });
 $('#softList').innerHTML = d.soft
  .map((skill) => `<span>${skill}</span>`)
  .join('');
 $('#langBtn').textContent = lang === 'id' ? 'EN' : 'ID';
 root.dataset.bsTheme = theme;
 $('#themeBtn').textContent = theme === 'dark' ? 'Light' : 'Dark';
 $('#fName').placeholder = lang === 'id' ? 'Nama Anda' : 'Your name';
}
/* ══════ 4. TOMBOL GANTI BAHASA & TEMA ══════ */
$('#langBtn').onclick = () => {
 lang = lang === 'id' ? 'en' : 'id';
 localStorage.setItem('lang', lang);
 apply();
};
$('#themeBtn').onclick = () => {
 theme = theme === 'dark' ? 'light' : 'dark';
 localStorage.setItem('theme', theme);
 apply();
};
/* ══════ 5. FORM KONTAK ══════
   Menyusun pesan lalu membuka WhatsApp. Nomor tujuan (6282220221024) bisa diganti di URL wa.me. */
$('#waForm').onsubmit = (event) => {
 event.preventDefault();

 const name = $('#fName').value.trim();
 const message = $('#fMsg').value.trim();

 if (!name || !message) {
  (name ? $('#fMsg') : $('#fName')).focus();
  return;
 }

 const whatsappUrl =
  'https://wa.me/6282220221024?text=' +
  encodeURIComponent(`Halo Narendra, saya ${name}.\n\n${message}`);

 window.open(whatsappUrl, '_blank', 'noopener');
};
/* ══════ 6. TAHUN FOOTER & JALANKAN ══════ */
$('#yr').textContent = new Date().getFullYear();
apply();
